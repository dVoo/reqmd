func TestWriteTargetPerPackagePrefix(t *testing.T) {
	tmp := t.TempDir()
	packages := []Package{
		{
			Name: "arith",
			Reqs: []model.GeneratedReq{
				{
					ID:     "IMP-arith-add-16962f2",
					Title:  "add",
					Status: "approved",
					Symbol: model.Symbol{Name: "add", Kind: "func", Package: "arith"},
				},
			},
		},
		{
			Name: "cli",
			Reqs: []model.GeneratedReq{
				{
					ID:     "IMP-cli-Run-deadbe",
					Title:  "Run",
					Status: "approved",
					Symbol: model.Symbol{Name: "Run", Kind: "func", Package: "cli"},
				},
			},
		},
	}
	if err := WriteTarget(tmp, packages, "IMP-"); err != nil {
		t.Fatalf("WriteTarget: %v", err)
	}

	// Each per-package schema should declare a unique, package-specific
	// prefix derived from the global --id-prefix flag + package name.
	arithSchema, err := os.ReadFile(filepath.Join(tmp, "arith", "schema.yaml"))
	if err != nil {
		t.Fatalf("read arith schema: %v", err)
	}
	if !strings.Contains(string(arithSchema), `id-prefix: IMP-arith-`) {
		t.Errorf("arith schema missing per-package prefix IMP-arith-; got:\n%s", arithSchema)
	}

	cliSchema, err := os.ReadFile(filepath.Join(tmp, "cli", "schema.yaml"))
	if err != nil {
		t.Fatalf("read cli schema: %v", err)
	}
	if !strings.Contains(string(cliSchema), `id-prefix: IMP-cli-`) {
		t.Errorf("cli schema missing per-package prefix IMP-cli-; got:\n%s", cliSchema)
	}

	// Top-level schema keeps the original (no per-package override).
	topSchema, err := os.ReadFile(filepath.Join(tmp, "schema.yaml"))
	if err != nil {
		t.Fatalf("read top-level schema: %v", err)
	}
	if !strings.Contains(string(topSchema), `id-prefix: "IMP-"`) {
		t.Errorf("top-level schema lost its default prefix IMP-; got:\n%s", topSchema)
	}

	// No per-package schema should still carry the bare "IMP-" prefix —
	// that is exactly the regression we are fixing.
	if strings.Contains(string(arithSchema), `id-prefix: IMP-`) && !strings.Contains(string(arithSchema), `id-prefix: IMP-arith-`) {
		t.Error("arith schema still declares the bare IMP- prefix (would collide)")
	}
	if strings.Contains(string(cliSchema), `id-prefix: IMP-`) && !strings.Contains(string(cliSchema), `id-prefix: IMP-cli-`) {
		t.Error("cli schema still declares the bare IMP- prefix (would collide)")
	}

	// Sanity: a custom --id-prefix flows through end-to-end.
	tmp2 := t.TempDir()
	if err := WriteTarget(tmp2, []Package{
		{
			Name: "foo",
			Reqs: []model.GeneratedReq{{ID: "MY-foo-X-1234567", Status: "approved"}},
		},
	}, "MY-"); err != nil {
		t.Fatalf("WriteTarget (custom prefix): %v", err)
	}
	fooSchema, err := os.ReadFile(filepath.Join(tmp2, "foo", "schema.yaml"))
	if err != nil {
		t.Fatalf("read foo schema: %v", err)
	}
	if !strings.Contains(string(fooSchema), `id-prefix: MY-foo-`) {
		t.Errorf("custom id-prefix did not flow through; got:\n%s", fooSchema)
	}
}

func TestQuoteIfNeeded(t *testing.T) {
	cases := []struct {
		name string
		in   string
		want string
	}{
		// Empty string: must quote (so `key: ` does not collapse to null).
		{"empty", "", `""`},
		// Plain values: pass through unquoted.
		{"plain", "foo", "foo"},
		{"plain path", "/tmp/source.go", "/tmp/source.go"},
		{"plain symbol kind", "function", "function"},
		// Characters that confuse YAML flow scalars.
		{"colon", "weird:name", `"weird:name"`},
		{"hash", "weird # comment", `"weird # comment"`},
		{"double quote", `say "hi"`, `"say \"hi\""`},
		{"single quote", "it's fine", `"it's fine"`},
		{"newline mid", "line1\nline2", `"line1\nline2"`},
		{"tab mid", "col1\tcol2", `"col1\tcol2"`},
		// Leading/trailing whitespace and YAML list markers.
		{"leading space", " foo", `" foo"`},
		{"trailing space", "foo ", `"foo "`},
		{"leading tab", "\tfoo", `"\tfoo"`},
		{"leading dash", "-foo", `"-foo"`},
		{"leading star", "*foo", `"*foo"`},
		// Backslash must be escaped.
		{"backslash", `C:\Users\foo`, `"C:\\Users\\foo"`},
		// Windows path with colon AND backslash.
		{"windows path", `C:\Users\foo\bar.go`, `"C:\\Users\\foo\\bar.go"`},
		// Combined: a real on-disk path that contains a colon.
		{"path with colon", "/tmp/weird:dir/file.go", `"/tmp/weird:dir/file.go"`},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			got := quoteIfNeeded(c.in)
			if got != c.want {
				t.Errorf("quoteIfNeeded(%q) = %q, want %q", c.in, got, c.want)
			}
		})
	}
}

// TestQuoteIfNeededRoundTrip verifies that values containing YAML-special
// characters (newlines, tabs, quotes, backslashes) survive a round-trip
// through a YAML parser unchanged. This is the regression test for the
// earlier bug where \n and \t were not escaped, causing YAML to fold the
// line break to a space.
func TestQuoteIfNeededRoundTrip(t *testing.T) {
	cases := []string{
		"line1\nline2",
		"col1\tcol2",
		"col1\ncol2\tcol3",
		"say \"hi\"",
		`C:\Users\foo`,
		"normal",
		"",
		`weird: "value" with \backslash`,
	}
	for _, in := range cases {
		t.Run(in, func(t *testing.T) {
			quoted := quoteIfNeeded(in)
			var out any
			if err := yaml.Unmarshal([]byte(quoted), &out); err != nil {
				t.Fatalf("yaml.Unmarshal(%q): %v", quoted, err)
			}
			if out != in {
				t.Errorf("round-trip lost data: in=%q out=%v", in, out)
			}
		})
	}
}
